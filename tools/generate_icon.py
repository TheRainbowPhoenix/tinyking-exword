#!/usr/bin/env python3
"""Build TKING's original 32x32 RGB565 crown for Edelweiss's EDL metadata.

No third-party image libraries needed. `--check` ensures the committed C
initializer and preview match the art generator (useful for CI).
"""
from __future__ import annotations

import argparse
from pathlib import Path
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
SIZE = 32


def rgb565(rgb: tuple[int, int, int]) -> int:
    red, green, blue = rgb
    return (red >> 3) << 11 | (green >> 2) << 5 | (blue >> 3)


COLORS = {name: rgb565(rgb) for name, rgb in {
    "night": (22, 15, 46),
    "violet": (34, 23, 68),
    "edge": (69, 45, 90),
    "ink": (67, 34, 46),
    "shadow": (151, 75, 31),
    "gold": (241, 164, 43),
    "light": (255, 214, 95),
    "shine": (255, 248, 183),
    "ruby": (225, 63, 92),
    "ruby_light": (255, 158, 168),
    "teal": (40, 194, 202),
    "aqua": (151, 252, 233),
}.items()}

pixels = [[COLORS["night"] for _ in range(SIZE)] for _ in range(SIZE)]


def point(x: int, y: int, color: str) -> None:
    if 0 <= x < SIZE and 0 <= y < SIZE:
        pixels[y][x] = COLORS[color]


def rect(x0: int, y0: int, x1: int, y1: int, color: str) -> None:
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            point(x, y, color)


def polygon(pts: list[tuple[int, int]], color: str) -> None:
    # Pixel-center even/odd fill, no PIL dependency.
    for y in range(SIZE):
        for x in range(SIZE):
            xx, yy = x + 0.5, y + 0.5
            inside = False
            for i, (ax, ay) in enumerate(pts):
                bx, by = pts[(i + 1) % len(pts)]
                if (ay > yy) != (by > yy) and xx < (bx - ax) * (yy - ay) / (by - ay) + ax:
                    inside = not inside
            if inside:
                point(x, y, color)


# Deep violet badge with a few restrained stars. The EBrew tile is only 32px.
rect(1, 1, 30, 30, "violet")
rect(2, 2, 29, 29, "night")
for x, y in ((4, 4), (27, 4), (3, 23), (28, 25)):
    point(x, y, "edge")
for x, y in ((5, 5), (26, 6), (4, 26), (28, 23)):
    point(x, y, "shine")
point(5, 4, "light")
point(26, 5, "light")

# Three-pronged crown, dark pixel-art outline and thick golden silhouette.
polygon([(3, 10), (10, 14), (15, 3), (21, 14), (29, 10), (26, 24), (6, 24)], "ink")
polygon([(5, 12), (11, 16), (15, 5), (20, 16), (27, 12), (24, 22), (8, 22)], "gold")
polygon([(7, 14), (12, 17), (15, 7), (17, 13), (15, 20), (9, 20)], "light")
polygon([(23, 15), (26, 13), (23, 21), (19, 21)], "shadow")

# Prong caps and tiny light catching the tips.
rect(14, 3, 16, 5, "light")
point(15, 3, "shine")
rect(3, 9, 5, 11, "light")
point(4, 9, "shine")
rect(27, 9, 29, 11, "light")
point(28, 9, "shine")

# Heavy gold base/rim. The dark separation is readable at actual 1x size.
rect(5, 21, 26, 27, "ink")
rect(7, 22, 24, 26, "gold")
rect(7, 22, 24, 22, "shine")
rect(8, 26, 23, 26, "shadow")
point(8, 24, "light")
point(23, 24, "light")

# Prominent turquoise diamond, and two little rubies in the rim.
polygon([(15, 21), (19, 24), (15, 27), (11, 24)], "ink")
polygon([(15, 22), (18, 24), (15, 26), (12, 24)], "teal")
point(14, 23, "aqua")
point(15, 23, "aqua")
rect(8, 23, 9, 24, "ruby")
point(8, 23, "ruby_light")
rect(21, 23, 22, 24, "ruby")
point(21, 23, "ruby_light")

# Tiny crown shadow grounds the silhouette in the tile.
rect(8, 28, 23, 28, "edge")

flat = [value for row in pixels for value in row]
assert len(flat) == 1024 and all(0 <= value <= 0xffff for value in flat)

header = [
    "/* Generated by tools/generate_icon.py; 32x32 opaque RGB565, row-major. */",
    "#ifndef TK_ICON_H",
    "#define TK_ICON_H",
    "#define TINYKING_ICON_PIXELS \\",
]
for row in range(SIZE):
    values = ", ".join(f"0x{v:04x}" for v in flat[row * SIZE:(row + 1) * SIZE])
    header.append("    " + values + ("," if row != 31 else "") + (" \\" if row != 31 else ""))
header.append("#endif")
header_text = "\n".join(header) + "\n"


def png_chunk(kind: bytes, data: bytes) -> bytes:
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xffffffff)


def make_png(scale: int = 8) -> bytes:
    # Preview nearest-neighbor RGB PNG. The RGB values come from RGB565 so it
    # shows exactly what the EX-word screen will receive (enlarged only).
    rgb = []
    for row in pixels:
        scan = bytearray()
        for value in row:
            r = ((value >> 11) & 31) * 255 // 31
            g = ((value >> 5) & 63) * 255 // 63
            b = (value & 31) * 255 // 31
            scan += bytes((r, g, b)) * scale
        rgb.extend([b"\x00" + scan] * scale)
    width = height = SIZE * scale
    return (b"\x89PNG\r\n\x1a\n" + png_chunk(b"IHDR", struct.pack(">2I5B", width, height, 8, 2, 0, 0, 0)) +
            png_chunk(b"IDAT", zlib.compress(b"".join(rgb), 9)) + png_chunk(b"IEND", b""))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Fail if the committed outputs are out of sync")
    args = parser.parse_args()
    files = {
        ROOT / "src" / "icon.h": header_text.encode("ascii"),
        ROOT / "docs" / "tking-crown.png": make_png(),
    }
    if args.check:
        for path, wanted in files.items():
            if not path.exists() or path.read_bytes() != wanted:
                raise SystemExit(f"Out of date: {path.relative_to(ROOT)}. Run python3 tools/generate_icon.py")
        print("TKING crown icon (32x32 RGB565) is current")
        return
    for path, content in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
        print(f"Wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
